import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {HUNT_ZONES,HUNT_BOSSES,HUNT_CRAFTS} from './hunt-data.js';
import {HUNT_LOOT_PRICES_V55,craftMaterialReserveV55,huntLootQuoteV55,sellHuntLootV55} from './hunt-loot-market-v55.js';
import {bagUsed,initBag} from './inventory-v29.js';
const game=readFileSync(new URL('./hunt.js',import.meta.url),'utf8');
const build=readFileSync(new URL('./build-vercel.mjs',import.meta.url),'utf8');
const everyDrop=new Set([...HUNT_ZONES.flatMap(z=>z.mobs.map(m=>m.material)),...HUNT_BOSSES.map(b=>b.material)]);
assert.deepEqual(new Set(Object.keys(HUNT_LOOT_PRICES_V55)),everyDrop,'all monsters have server-defined vendor quotes');
assert.equal(HUNT_BOSSES.length,4);
for(const boss of HUNT_BOSSES)assert.equal(HUNT_LOOT_PRICES_V55[boss.material].rarity,'boss');
const state={coins:5000,hunt:{materials:{'젤리 조각':18,'왕의 도토리':1,'버섯 포자':14,'미등록 재료':200}},
 fashion:{owned:[]}};
initBag(state);
const before=bagUsed(state),original=JSON.stringify(state.hunt.materials);
const needed=HUNT_CRAFTS.find(r=>r.gives==='fashion_outfit_19').requires[0][1];
assert.equal(needed,12);
assert.equal(craftMaterialReserveV55('젤리 조각',[]),needed);
let q=huntLootQuoteV55(state,'젤리 조각');
assert.equal(q.have,18);assert.equal(q.reserve,12);assert.equal(q.surplus,6);
let item=sellHuntLootV55(state,'젤리 조각',7,{level:57});
assert.equal(item.ok,false,'protected recipe ingredients must not sell by default');
assert.equal(JSON.stringify(state.hunt.materials),original);
item=sellHuntLootV55(state,'젤리 조각',5,{level:57});
assert.equal(item.ok,true);assert.equal(item.sold,5);
assert.equal(state.hunt.materials['젤리 조각'],13);
assert.equal(item.gross,HUNT_LOOT_PRICES_V55['젤리 조각'].unitPrice*5);
assert(item.earned>0&&item.earned<=item.gross,'daily market cap applies');
assert.equal(bagUsed(state),before-5,'selling materials frees bag slots');
item=sellHuntLootV55(state,'왕의 도토리',1,{level:57});
assert.equal(item.ok,false,'unique boss crafting drop is protected');
item=sellHuntLootV55(state,'왕의 도토리',1,{level:57,includeProtected:true});
assert.equal(item.ok,true,'explicit confirmed recipe override can sell boss loot');
assert.equal(state.hunt.materials['왕의 도토리'],0);
assert.equal(state.hunt.materials['미등록 재료'],200,'unlisted legacy materials are untouched');
const nowCoins=state.coins;
assert.equal(sellHuntLootV55(state,'미등록 재료',1,{level:57}).ok,false);
assert.equal(state.coins,nowCoins);
assert.equal(sellHuntLootV55(state,'버섯 포자',21,{level:57}).ok,false,'single-click sale cap');
assert.equal(sellHuntLootV55(state,'버섯 포자',-1,{level:57}).ok,false);
assert.equal(sellHuntLootV55(state,'버섯 포자',1.5,{level:57}).ok,false);
const reserve=craftMaterialReserveV55('젤리 조각',['fashion_outfit_19']);
assert.equal(reserve,0,'after collecting costume the remaining material is sellable');
assert.equal(huntLootQuoteV55({...state,fashion:{owned:['fashion_outfit_19']}},'젤리 조각').available,13);
assert(game.includes('function openHuntSalvageShopV55()'));
assert(game.includes("id=\"openHuntSalvageShop\""),'vendor must be reachable from hunt map');
assert(game.includes("id=\"openLootSellerV55\""),'vendor must be reachable from crafting');
assert(game.includes('sellHuntLootV55(state,name,quantity'), 'NPC UI must use known-price transaction helper');
assert(game.includes("data-hunt-sell-protected"),'rare materials need explicit warning');
assert(build.includes("'hunt-loot-market-v55.js'"),'Cloudflare static asset should publish vendor helper');
console.log('PASS v55 loot: 6 zones full catalog, reserved costume mats, boss protection, 1/5/20 sales, bag freeing, soft-capped gold and vendor navigation');
