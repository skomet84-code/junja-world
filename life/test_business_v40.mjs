import assert from 'node:assert/strict';
import {startingEconomy} from './secure-economy-v36.js';
import {selectProfession} from './professions-v39.js';
import {buildWorkshop,upgradeWorkshop,manufactureWorkshopItem,WORKSHOP_PRODUCTS,workshopView,businessWeekBeginning} from './business-v40.js';
import {MARKET_CATALOG,marketQuote} from './player-market-v38.js';
const t=new Date('2026-10-19T12:00:00+09:00');
let initial=startingEconomy();initial.coins=40000;initial.stock={berry:8,wheat:5,apple:4,carrot:9};
initial=selectProfession(initial,'farmer',{},t).next;
assert.throws(()=>buildWorkshop(initial,'farmer',{},t),/숙련/);
assert.throws(()=>buildWorkshop(initial,'chef',{harvest:100},t),/현재 직업/);
const built=buildWorkshop(initial,'farmer',{harvest:10},t);
assert.equal(initial.workshops,undefined,'Wallet snapshots are immutable');
assert.equal(built.next.workshops.farmer.level,1);
assert.equal(built.delta,-3100);
assert.throws(()=>buildWorkshop(built.next,'farmer',{harvest:10},t),/이미/);
const factory=manufactureWorkshopItem(built.next,'farmer',{harvest:10});
assert.equal(factory.next.stock.berry,5,'Exact inputs consumed once');
assert.equal(factory.next.stock.berry_box,1);
assert.equal(factory.next.coins,built.next.coins-130);
assert.equal(built.next.stock.berry,8);
assert.equal(factory.product,'berry_box');
assert.throws(()=>upgradeWorkshop(factory.next,'farmer',{harvest:10}),/숙련도/);
const improved=upgradeWorkshop(factory.next,'farmer',{harvest:50});
assert.equal(improved.next.workshops.farmer.level,2);
assert.equal(workshopView(improved.next,{harvest:50},t).costs.farmer.production,124,'Five percent operating cost discount');
const final=upgradeWorkshop(improved.next,'farmer',{harvest:200});
assert.equal(final.next.workshops.farmer.level,3);
assert.equal(workshopView(final.next,{harvest:200},t).costs.farmer.production,117);
assert.throws(()=>upgradeWorkshop(final.next,'farmer',{harvest:200}),/최고/);
assert.equal(Object.keys(WORKSHOP_PRODUCTS).length,3);
for(const id of Object.keys(WORKSHOP_PRODUCTS)){
 const m=WORKSHOP_PRODUCTS[id];
 assert.equal(marketQuote(id,m.sell,1).item,id,'Special production item sells via player market');
 assert.equal(MARKET_CATALOG[id].sell,m.sell);
}
const poor=structuredClone(initial);poor.coins=5;
assert.throws(()=>buildWorkshop(poor,'farmer',{harvest:10},t),/골드/);
const lacking=structuredClone(built.next);lacking.stock.berry=1;
assert.throws(()=>manufactureWorkshopItem(lacking,'farmer',{harvest:10}),/농산물/);
assert.equal(businessWeekBeginning(new Date('2026-10-18T23:59:00+09:00')).toISOString(),'2026-10-11T15:00:00.000Z');
assert.equal(businessWeekBeginning(new Date('2026-10-19T00:00:00+09:00')).toISOString(),'2026-10-18T15:00:00.000Z');
console.log('PASS v40 professions, upgrades, exact production stock, market catalog and weekly KST reset');
