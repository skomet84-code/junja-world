import assert from 'node:assert/strict';
import {startingEconomy} from './secure-economy-v36.js';
import {ENERGY_MAX,ENERGY_REGEN_SECONDS,ENERGY_COSTS,ENERGY_PRICE_G,
 projectEnergy,chargeEnergy,buyEnergy} from './action-energy-v47.js';
const time=new Date('2026-10-19T12:00:00+09:00');
const t=time.getTime(),s=startingEconomy();s.coins=8500;
assert.equal(ENERGY_MAX,100);
assert.equal(ENERGY_REGEN_SECONDS,360);
assert.equal(ENERGY_PRICE_G,1200);
assert.deepEqual(ENERGY_COSTS,{plant:2,harvest:0,gather:3,fish:5,craft:6,order:3,business_produce:8});
assert.equal(projectEnergy(s,time).current,100,'Existing save without energy initializes full without rewriting old level');
const gathered=chargeEnergy(s,'gather',time);assert.equal(gathered.energy.current,97);
const fished=chargeEnergy(s,'fish',time);assert.equal(fished.energy.current,95);
const a=chargeEnergy(s,'plant',time);
assert.equal(a.energy.current,98);
assert.equal(a.cost,2);
assert.equal(s.actionEnergyV47,undefined,'Legacy original snapshot unchanged');
assert.equal(projectEnergy(a.next,new Date(t+359000)).current,98);
assert.equal(projectEnergy(a.next,new Date(t+360000)).current,99);
assert.equal(projectEnergy(a.next,new Date(t+2*360000)).current,100);
assert.equal(projectEnergy(a.next,new Date(t+72*360000)).current,100);
assert.equal(projectEnergy(a.next,new Date(t+72*360000)).nextRegenSeconds,0);
const rested=chargeEnergy(a.next,'craft',new Date(t+720000));
assert.equal(rested.energy.current,94);
const noMore=structuredClone(s);noMore.actionEnergyV47={current:2,at:t,packsDay:'',packs:0};
assert.equal(chargeEnergy(noMore,'harvest',time).energy.current,2,'harvest is free; planting already consumed energy');
assert.equal(chargeEnergy(noMore,'sell',time).energy.current,2,'Selling inventory does not consume energy');
const buy=buyEnergy(noMore,time);
assert.equal(buy.next.coins,7300);
assert.equal(buy.energy.current,27);
assert.equal(buy.energy.packsUsed,1);
assert.equal(noMore.coins,8500);
const day2=new Date('2026-10-20T12:00:00+09:00');
assert.equal(projectEnergy(buy.next,day2).packsUsed,0,'KST daily shop limit resets');
const used=structuredClone(noMore);
used.actionEnergyV47={current:1,at:t,packsDay:'2026-10-19',packs:3};
assert.throws(()=>buyEnergy(used,time),/3번/);
const full=startingEconomy();full.coins=10000;
assert.throws(()=>buyEnergy(full,time),/최대치/);
const broke=structuredClone(noMore);broke.coins=1000;
assert.throws(()=>buyEnergy(broke,time),/부족/);
const corrupt=structuredClone(noMore);corrupt.actionEnergyV47.at=t+60000;
assert.throws(()=>projectEnergy(corrupt,time),/저장 기록/);
const negative=structuredClone(noMore);negative.actionEnergyV47.current=-4;
assert.throws(()=>projectEnergy(negative,time),/저장 기록/);
const cap=structuredClone(noMore);cap.actionEnergyV47.current=93;
assert.equal(buyEnergy(cap,time).energy.current,100,'Cannot overfill beyond 100');
console.log('PASS v47 server energy: 100cap, 6min recovery, plant=2 harvest=free 6/8 costs, 1200G packs, KST 3/day limits, strict anti-corruption');
