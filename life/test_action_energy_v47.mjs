import assert from 'node:assert/strict';
import {startingEconomy} from './secure-economy-v36.js';
import {ENERGY_MAX,ENERGY_REGEN_SECONDS,ENERGY_COSTS,ENERGY_PRICE_G,
 nextEnergyPrice,projectEnergy,chargeEnergy,buyEnergy} from './action-energy-v47.js';
const time=new Date('2026-10-19T12:00:00+09:00'),t=time.getTime();
const s=startingEconomy();s.coins=8500;
assert.equal(ENERGY_MAX,200);
assert.equal(ENERGY_REGEN_SECONDS,180);
assert.equal(ENERGY_PRICE_G,1000);
assert.deepEqual(ENERGY_COSTS,{plant:2,harvest:0,gather:3,fish:5,craft:6,order:3,business_produce:8});
assert.equal(projectEnergy(s,time).current,200,'new and legacy saves initialize full without changing level');
assert.equal(projectEnergy(s,time).packPrice,1000);
const legacyEnergy=structuredClone(s);
legacyEnergy.actionEnergyV47={current:100,at:t,packsDay:'',packs:0};
assert.equal(projectEnergy(legacyEnergy,time).current,100,'existing player energy is preserved without a reset');
assert.equal(projectEnergy(legacyEnergy,time).max,200,'old players receive the higher capacity');
assert.equal(projectEnergy(legacyEnergy,new Date(t+180000)).current,101,'old saves recover at the faster rate');
assert.equal(legacyEnergy.actionEnergyV47.current,100,'read projections cannot mutate persisted records');
const gather=chargeEnergy(s,'gather',time);assert.equal(gather.energy.current,197);
const fish=chargeEnergy(s,'fish',time);assert.equal(fish.energy.current,195);
const a=chargeEnergy(s,'plant',time);
assert.equal(a.energy.current,198);assert.equal(a.cost,2);
assert.equal(s.actionEnergyV47,undefined,'previous account snapshot remains unchanged');
assert.equal(projectEnergy(a.next,new Date(t+179000)).current,198);
assert.equal(projectEnergy(a.next,new Date(t+180000)).current,199);
assert.equal(projectEnergy(a.next,new Date(t+360000)).current,200);
const harvest=chargeEnergy(a.next,'harvest',new Date(t+180000));
assert.equal(harvest.cost,0,'server trial farm harvest stays free');
assert.equal(harvest.energy.current,199);
const rested=chargeEnergy(a.next,'craft',new Date(t+360000));
assert.equal(rested.energy.current,194);
const exhausted=structuredClone(s);
exhausted.actionEnergyV47={current:2,at:t,packsDay:'',packs:0};
assert.equal(chargeEnergy(exhausted,'sell',time).energy.current,2);
const first=buyEnergy(exhausted,time);
assert.equal(first.delta,-1000);
assert.equal(first.next.coins,7500);
assert.equal(first.energy.current,27);
assert.equal(first.energy.packsUsed,1);
assert.equal(first.energy.packPrice,2000);
assert.equal(exhausted.coins,8500,'buyer source object immutable');
assert.equal(projectEnergy(first.next,time).packPrice,2000);
const second=buyEnergy(first.next,time);
assert.equal(second.delta,-2000);
assert.equal(second.next.coins,5500);
assert.equal(second.energy.current,52);
assert.equal(second.energy.packsUsed,2);
assert.equal(second.energy.packPrice,4000);
const third=buyEnergy(second.next,time);
assert.equal(third.delta,-4000);
assert.equal(third.next.coins,1500);
assert.equal(third.energy.packsUsed,3);
assert.equal(third.energy.packPrice,8000,'fourth purchase price doubles, never 3/day hard cap');
assert.throws(()=>buyEnergy(third.next,time),/부족/,'price/coins, NOT daily count, may stop purchase');
let rich=startingEconomy();rich.coins=100000;
rich.actionEnergyV47={current:0,at:t,packsDay:'2026-10-19',packs:0};
const paid=[];
for(let i=0;i<6;i++){
 const expected=1000*(2**i);
 const receipt=buyEnergy(rich,time);
 assert.equal(receipt.delta,-expected);
 assert.equal(receipt.energy.packsUsed,i+1);
 assert.equal(receipt.energy.packPrice,nextEnergyPrice(i+1));
 paid.push(receipt.delta);
 rich=receipt.next;
 rich.actionEnergyV47.current=0; // simulate legitimately spending energy after each top-up
 if(i===5)break;
}
assert.deepEqual(paid,[-1000,-2000,-4000,-8000,-16000,-32000]);
assert.equal(rich.coins,37000);
assert.equal(rich.actionEnergyV47.packs,6,'sixth purchase is legal on the same KST day');
const day2=new Date('2026-10-20T00:00:00+09:00');
rich.actionEnergyV47.current=0;
rich.actionEnergyV47.at=day2.getTime();
const rollover=projectEnergy(rich,day2);
assert.equal(rollover.packsUsed,0,'KST midnight resets escalating price');
assert.equal(rollover.packPrice,1000);
const restart=buyEnergy(rich,day2);
assert.equal(restart.delta,-1000);
assert.equal(restart.energy.packsUsed,1);
assert.equal(restart.energy.packPrice,2000);
const beforeMidnight=new Date('2026-10-19T23:59:59+09:00');
assert.equal(projectEnergy(exhausted,beforeMidnight).packPrice,1000);
assert.equal(nextEnergyPrice(0),1000);
assert.equal(nextEnergyPrice(1),2000);
assert.equal(nextEnergyPrice(2),4000);
assert.equal(nextEnergyPrice(3),8000);
assert.equal(nextEnergyPrice(29),536870912000);
assert.equal(nextEnergyPrice(30),null,'price exceeds 1 trillion wallet ceiling, not count limit');
assert.throws(()=>nextEnergyPrice(-1),/올바르지/);
const overflow=startingEconomy();
overflow.coins=1_000_000_000_000;
overflow.actionEnergyV47={current:0,at:t,packsDay:'2026-10-19',packs:30};
assert.equal(projectEnergy(overflow,time).packPrice,null);
assert.throws(()=>buyEnergy(overflow,time),/한도/);
const malformed=structuredClone(exhausted);
malformed.actionEnergyV47.at=t+60000;
assert.throws(()=>projectEnergy(malformed,time),/저장 기록/);
const negative=structuredClone(exhausted);
negative.actionEnergyV47.current=-4;
assert.throws(()=>projectEnergy(negative,time),/저장 기록/);
const invalidCount=structuredClone(exhausted);
invalidCount.actionEnergyV47.packs=-1;
assert.throws(()=>projectEnergy(invalidCount,time),/저장 기록/);
const full=startingEconomy();full.coins=10000;
assert.throws(()=>buyEnergy(full,time),/최대치/);
const broke=structuredClone(exhausted);broke.coins=900;
assert.throws(()=>buyEnergy(broke,time),/부족/);
const cap=structuredClone(exhausted);cap.actionEnergyV47.current=193;
assert.equal(buyEnergy(cap,time).energy.current,200,'cannot overfill beyond 200');
console.log('PASS v62 energy: unlimited purchases / 1000→2000→4000→8000→16000→32000, KST midnight reset, 200 cap, 180s regen, integer-safe pricing, no old save changes');
