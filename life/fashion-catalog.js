export const DEFAULT_FASHION=Object.freeze({hair:null,outfit:null,accessory:null,pet:null});
export function validFashion(value){
 const result={...DEFAULT_FASHION};
 for(const type of Object.keys(result)){
  const id=value?.[type];
  if(typeof id==='string'&&CATALOG_BY_ID[id]?.type===type)result[type]=id;
 }
 return result;
}
export function petBonus(petId,kind){
 const pet=CATALOG_BY_ID[petId];
 if(!pet||pet.type!=='pet')return 0;
 // Bonuses never affect speed/pathfinding: v18 movement is deliberately locked.
 return kind==='gather'?pet.bonus:kind==='harvest'?pet.bonus*3:
 kind==='delivery'?pet.bonus*4:kind==='fish'?pet.bonus*2:0;
}
