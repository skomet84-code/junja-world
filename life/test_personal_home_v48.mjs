import assert from 'node:assert/strict';
import {startingEconomy} from './secure-economy-v36.js';
import {FURNITURE_V48,HOUSE_LEVELS,houseView,homeAction} from './personal-home-v48.js';
const fresh=startingEconomy();fresh.coins=250000;
const zero=houseView(fresh,{sales:0,craft:0});
assert.equal(zero.house.level,1);
assert.equal(zero.house.wall,'cream');
assert.equal(zero.house.floor,'oak');
assert.deepEqual(zero.house.placed,[{slot:5,item:'oak_chair',turn:0}]);
