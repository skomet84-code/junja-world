assert.equal(fresh.houseV48,undefined,'Original trial profile must remain unchanged');
assert.throws(()=>homeAction(fresh,'buy',{item:'crystal_lamp'},{}),/업적/);
assert.throws(()=>homeAction(fresh,'buy',{item:'unknown'},{}),/없는/);
assert.throws(()=>homeAction(fresh,'place',{item:'oak_chair',slot:3},{}),/부족/);
assert.throws(()=>homeAction(fresh,'place',{item:'oak_chair',slot:5},{}),/배치/);
let h=homeAction(fresh,'buy',{item:'leaf_plant'},{sales:0,craft:0});
assert.equal(h.delta,-450);
assert.equal(h.next.coins,249550);
assert.equal(h.next.houseV48.owned.leaf_plant,1);
assert.equal(fresh.coins,250000,'No mutation of prior checkpoint snapshot');
let p=homeAction(h.next,'place',{slot:4,item:'leaf_plant',turn:2},{});
assert.equal(p.delta,0);
assert.equal(p.next.coins,h.next.coins);
assert.equal(p.next.houseV48.placed.find(x=>x.slot===4).turn,2);
assert.throws(()=>homeAction(p.next,'place',{slot:4,item:'oak_chair'},{}),/이미/);
let rotated=homeAction(p.next,'rotate',{slot:4},{});
assert.equal(rotated.next.houseV48.placed.find(x=>x.slot===4).turn,3);
rotated=homeAction(rotated.next,'rotate',{slot:4},{});
assert.equal(rotated.next.houseV48.placed.find(x=>x.slot===4).turn,0);
const r=homeAction(rotated.next,'remove',{slot:4},{});
assert.equal(r.next.houseV48.placed.length,1);
assert.equal(r.next.houseV48.owned.leaf_plant,1,'Stored furnishings remain owned');
assert.throws(()=>homeAction(r.next,'place',{slot:16,item:'leaf_plant'},{}),/위치/);
let upgraded=homeAction(r.next,'upgrade',{},{}),v=houseView(upgraded.next,{sales:3,craft:0});
assert.equal(upgraded.delta,-8000);
assert.equal(upgraded.next.houseV48.level,2);
assert.equal(v.catalog.crystal_lamp.unlocked,true,'Real sales receipts unlock crystal rarity');
assert.throws(()=>homeAction(upgraded.next,'buy',{item:'royal_piano'},{sales:3,craft:0}),/업적/);
const bought=homeAction(upgraded.next,'buy',{item:'crystal_lamp'},{sales:3,craft:0});
assert.equal(bought.delta,-9800);
assert.equal(bought.next.houseV48.owned.crystal_lamp,1);
assert.equal(houseView(bought.next,{}).catalog.crystal_lamp.unlocked,false,'Achievements are recalculated from actual sale receipts');
assert.throws(()=>homeAction(bought.next,'buy',{item:'crystal_lamp'},{sales:10,craft:12}),/한도/);
const gold=homeAction(bought.next,'upgrade',{},{}); // 3rd tier
assert.equal(gold.delta,-30000);
assert.equal(gold.next.houseV48.level,3);
assert.equal(houseView(gold.next,{craft:8,sales:0}).catalog.royal_piano.unlocked,true);
const boughtPiano=homeAction(gold.next,'buy',{item:'royal_piano'},{sales:0,craft:8});
assert.equal(boughtPiano.next.houseV48.owned.royal_piano,1);
assert.throws(()=>homeAction(gold.next,'buy',{item:'royal_chandelier'},{sales:999,craft:999}),/업적/);
const final=homeAction(boughtPiano.next,'upgrade',{},{}); // level 4
assert.equal(final.next.houseV48.level,4);
assert.equal(final.delta,-120000);
assert.equal(houseView(final.next,{sales:8,craft:15}).catalog.royal_chandelier.unlocked,true);
assert.equal(homeAction(final.next,'style',{kind:'wall',id:'amethyst'},{}).next.houseV48.wall,'amethyst');
assert.equal(homeAction(final.next,'style',{kind:'floor',id:'royal'},{}).next.houseV48.floor,'royal');
assert.throws(()=>homeAction(final.next,'upgrade',{},{}),/최고/);
