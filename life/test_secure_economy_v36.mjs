import assert from 'node:assert/strict';
import {startingEconomy,economyAction,economyView,economyDay,LAB_CROPS,LAB_ORDERS} from './secure-economy-v36.js';

const t=new Date('2026-10-18T04:00:00Z');
const beginning=startingEconomy();
assert.equal(beginning.coins,1500);
assert.equal(beginning.plots.length,6);
assert.equal(economyDay(new Date('2026-10-18T16:00:00Z')),'2026-10-19','KST day must not use browser clock');
const planted=economyAction(beginning,'plant',{index:0,crop:'lettuce',cost:-99999},t);
assert.equal(planted.next.coins,1480);
assert.equal(beginning.coins,1500,'Reducer must never mutate its original DB snapshot');
assert.equal(planted.receipt.delta,-20);
assert.equal(planted.next.plots[0].crop,'lettuce');
assert.throws(()=>economyAction(planted.next,'plant',{index:0,crop:'lettuce'},t),/이미/);
assert.throws(()=>economyAction(planted.next,'harvest',{index:0},t),/아직/);
assert.throws(()=>economyAction(planted.next,'harvest',{index:-1},t),/존재하지/);
assert.throws(()=>economyAction(planted.next,'plant',{index:1,crop:'hacker'},t),/없습니다/);
assert.throws(()=>economyAction(planted.next,'sell',{item:'lettuce',quantity:100000000},t),/재고/);
const harvested=economyAction(planted.next,'harvest',{index:0},new Date(t.getTime()+60001));
assert.equal(harvested.next.stock.lettuce,1);
assert.equal(harvested.next.plots[0],null);
assert.equal(harvested.next.coins,1480);
const sold=economyAction(harvested.next,'sell',{item:'lettuce',sell:99999999},new Date(t.getTime()+61000));
assert.equal(sold.receipt.delta,34,'Sale price must come from server catalog only');
assert.equal(sold.next.coins,1514);
assert.equal(sold.next.stock.lettuce,0);
assert.throws(()=>economyAction(sold.next,'sell',{item:'lettuce'},t),/재고/);
assert.equal(LAB_ORDERS.length,3);

let s=startingEconomy();
s.stock={berry:3,lettuce:2,carrot:1};
let craft=economyAction(s,'craft',{recipe:'berry_jam'},t);
assert.equal(craft.next.coins,1390);
assert.equal(craft.next.stock.berry,0);
assert.equal(craft.next.stock.berry_jam,1);
assert.throws(()=>economyAction(craft.next,'craft',{recipe:'berry_jam'},t),/부족/);
const ordered=economyAction(craft.next,'order',{order:'food_delivery'},t);
assert.equal(ordered.next.reputation,4);
assert.equal(ordered.next.stats.delivered,1);
assert.equal(ordered.next.stock.lettuce,0);
assert.equal(ordered.next.stock.carrot,0);
assert.throws(()=>economyAction(ordered.next,'order',{order:'food_delivery'},t),/이미/);
const ordered2=economyAction(ordered.next,'order',{order:'cafe_delivery'},t);
assert.equal(ordered2.next.reputation,14);
assert.equal(ordered2.next.completed.length,2);
assert.equal(ordered2.next.stock.berry_jam,0);
const following=new Date(t.getTime()+86400000);
assert.equal(economyView(ordered2.next,following).orders[0].completed,false,'Next day refresh is display-only');
assert.equal(ordered2.next.reputation,14,'Rank persists between days');
assert.equal(ordered2.next.orderDay,economyDay(t),'Reading tomorrow must not mutate persisted day');
assert.throws(()=>economyAction(ordered2.next,'order',{order:'festival_delivery'},t),/두 건/);
const upgraded=startingEconomy();
upgraded.coins=5000;
let expanded=economyAction(upgraded,'expand',{},t);
assert.equal(expanded.next.plots.length,12);
assert.equal(expanded.next.coins,200);
assert.equal(upgraded.plots.length,6,'Prior plot array must not mutate on upgrade');
assert.throws(()=>economyAction(expanded.next,'expand',{},t),/골드 부족|잔액/);
assert.equal(Object.keys(LAB_CROPS).length,5);
console.log('v36 server-only economy: authoritative prices, timer, KST day, unique orders, atomic reducer passed');
