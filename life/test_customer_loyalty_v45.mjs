import assert from 'node:assert/strict';
import {startingEconomy} from './secure-economy-v36.js';
import {selectProfession} from './professions-v39.js';
import {loyaltyTier,loyaltyView,vipQuote,fulfillVipOrder,weeklyStart,
 validateLoyaltyRows,weeklyScore,VIP_MIN_DISTINCT_DAYS} from './customer-loyalty-v45.js';
const now=new Date('2026-10-19T12:00:00+09:00');
const nextWeek=new Date('2026-10-26T12:00:00+09:00');
assert.equal(VIP_MIN_DISTINCT_DAYS,3);
assert.equal(loyaltyTier(0).title,'첫 방문');
assert.equal(loyaltyTier(3).title,'단골');
assert.equal(loyaltyTier(7).title,'VIP 단골');
assert.equal(loyaltyTier(15).title,'마을의 가족');
assert.equal(weeklyStart(now),'2026-10-18T15:00:00.000Z');
assert.equal(weeklyStart(nextWeek),'2026-10-25T15:00:00.000Z');
const proof=validateLoyaltyRows([{npc_id:'tobi',days:'3'},{npc_id:'rina',days:1}]);
assert.deepEqual(proof,{tobi:3,rina:1,yuni:0});
assert.throws(()=>validateLoyaltyRows([{npc_id:'admin',days:1000}]),/올바르지/);
assert.throws(()=>validateLoyaltyRows([{npc_id:'tobi',days:-3}]),/올바르지/);
assert.equal(vipQuote('tobi',now).quantity,2);
assert.equal(vipQuote('tobi',now).tax,Math.ceil(vipQuote('tobi',now).gross*.15));
assert.equal(vipQuote('tobi',now).fee,300);
assert.throws(()=>vipQuote('unknown',now),/존재하지/);
let state=startingEconomy();
state.coins=6000;state.stock={berry_box:3,artisan_tart:2};
state.workshops={farmer:{level:2},chef:{level:1}};
state=selectProfession(state,'farmer',{},now).next;
const locked=loyaltyView(state,{tobi:2},now);
assert.equal(locked.customers.find(x=>x.npcId==='tobi').canAccept,false);
assert.equal(locked.customers.find(x=>x.npcId==='tobi').remainingVisits,1);
assert.throws(()=>fulfillVipOrder(state,'tobi',{tobi:2},now),/단골 3회/);
assert.throws(()=>fulfillVipOrder(state,'rina',{rina:3},now),/현재 직업/);
const quote=vipQuote('tobi',now);
const fulfilled=fulfillVipOrder(state,'tobi',{tobi:3},now);
assert.equal(fulfilled.next.stock.berry_box,1);
assert.equal(fulfilled.next.coins,state.coins+quote.net);
assert.equal(state.stock.berry_box,3,'Old checkpoint snapshot must remain immutable');
assert.equal(fulfilled.next.vipOrders.weekStart,weeklyStart(now));
assert.equal(loyaltyView(fulfilled.next,{tobi:3},now).weeklyUsed,true);
assert.throws(()=>fulfillVipOrder(fulfilled.next,'tobi',{tobi:3},now),/이미 완료/);
assert.throws(()=>fulfillVipOrder(fulfilled.next,'rina',{rina:4},now),/이미 완료/);
assert.equal(loyaltyView(fulfilled.next,{tobi:3},nextWeek).weeklyUsed,false,'KST Monday resets VIP allocation');
const low=structuredClone(state);low.stock.berry_box=1;
assert.throws(()=>fulfillVipOrder(low,'tobi',{tobi:3},now),/2개/);
const broke=structuredClone(state);broke.coins=1_000_000_000_000;
assert.throws(()=>fulfillVipOrder(broke,'tobi',{tobi:3},now),/최대/);
const corrupted=structuredClone(state);corrupted.coins=-10;
assert.throws(()=>fulfillVipOrder(corrupted,'tobi',{tobi:3},now),/지갑/);
const board=weeklyScore([{name:'농장왕',sales:5,net:'9876',week_start:null},
 {name:'유니',sales:2,net:'1234'}]);
assert.equal(board[0].rank,1);
assert.equal(board[0].net,9876);
assert.equal(board[1].rank,2);
console.log('PASS v45 verified loyalty tiers, two real product consumption, 15% tax+fee, weekly idempotency, KST reset and immutable wallets');
