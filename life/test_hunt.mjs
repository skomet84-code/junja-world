import assert from 'node:assert/strict';
import {HUNT_ZONES,HUNT_BOSSES,HUNT_SKILLS,HUNT_CRAFTS,MAX_ACTIVE_ENEMIES,huntLevel,combatStats,enemyDamage,canCraft,zoneUnlocked,dailyBossKey} from './hunt-data.js';
assert.equal(HUNT_ZONES.length,4,'four hunt maps');
assert.deepEqual(HUNT_ZONES.map(z=>z.level),[3,8,15,25]);
assert.equal(HUNT_ZONES.reduce((n,z)=>n+z.mobs.length,0),20,'20 authored enemy types');
assert.equal(new Set(HUNT_ZONES.flatMap(z=>z.mobs.map(m=>m.id))).size,20,'unique monster ids');
assert.equal(HUNT_BOSSES.length,4,'four daily bosses');
assert.equal(MAX_ACTIVE_ENEMIES,7,'avoid rendering 20 monsters at once');
assert.equal(HUNT_SKILLS.length,3,'three basic skill buttons');
assert.deepEqual(HUNT_SKILLS.map(s=>s.cooldown),[3,7,20]);
assert(HUNT_BOSSES.every((b,i)=>b.zone===HUNT_ZONES[i].id));
assert(HUNT_ZONES.every((z,i)=>z.mobs.every(m=>m.hp<z.mobs.at(-1).hp*1.1)));
assert(HUNT_ZONES.every((z,i)=>HUNT_BOSSES[i].hp>Math.max(...z.mobs.map(m=>m.hp))));
assert.equal(huntLevel(0),1);assert.equal(huntLevel(320),3);
assert.equal(zoneUnlocked(HUNT_ZONES[0],2),false);
assert.equal(zoneUnlocked(HUNT_ZONES[0],3),true);
assert.equal(zoneUnlocked(HUNT_ZONES[3],24),false);
assert.equal(zoneUnlocked(HUNT_ZONES[3],25),true);
assert(combatStats(25).maxHp>combatStats(3).maxHp);
assert(enemyDamage(3,true,25)>enemyDamage(0,false,25));
assert.equal(dailyBossKey('meadow','2026-10-17'),'meadow:2026-10-17');
assert.equal(HUNT_CRAFTS.length,4);
const sample=HUNT_CRAFTS[0];
assert.equal(canCraft(sample,{},[],1e9),false);
assert.equal(canCraft(sample,Object.fromEntries(sample.requires),[],sample.coins),true);
assert.equal(canCraft(sample,Object.fromEntries(sample.requires),[sample.gives],1e8),false);
console.log('PASS: 4 separate hunting zones, 20 monsters, 4 daily bosses, 3 balanced skills, level gates and cosmetic loot crafting');
