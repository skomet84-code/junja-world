import assert from 'node:assert/strict';
import {startingEconomy} from './secure-economy-v36.js';
import {marketQuote,reserveListing,cancelListing,settleListing,MARKET_LISTING_FEE} from './player-market-v38.js';
const seller=startingEconomy();seller.stock.lettuce=5;seller.stock.berry_jam=1;
const buyer=startingEconomy();
assert.throws(()=>marketQuote('unknown',100,1),/거래 가능한/);
assert.throws(()=>marketQuote('lettuce',1,1),/가격은/);
assert.throws(()=>marketQuote('lettuce',10000,1),/가격은/);
assert.throws(()=>marketQuote('lettuce',34,21),/1~20/);
const listing=reserveListing(seller,'lettuce',34,2);
assert.equal(listing.state.stock.lettuce,3);
assert.equal(listing.state.coins,seller.coins-MARKET_LISTING_FEE);
assert.equal(seller.stock.lettuce,5,'Immutable seller snapshot');
const row={item:'lettuce',unit_price:'34',quantity:2};
const trade=settleListing(buyer,listing.state,row);
assert.equal(trade.quote.gross,68);
assert.equal(trade.quote.tax,4,'Ceiling 5% marketplace tax');
assert.equal(trade.quote.net,64);
assert.equal(trade.buyer.coins,1432);
assert.equal(trade.seller.coins,1552);
assert.equal(trade.buyer.stock.lettuce,2);
assert.equal(trade.seller.stock.lettuce,3,'Escrow is never removed again on purchase');
assert.equal(buyer.coins,1500,'Original buyer snapshot untouched');
const refunded=cancelListing(listing.state,row);
assert.equal(refunded.state.stock.lettuce,5);
assert.equal(refunded.state.coins,1488,'Nonrefundable listing fee is an explicit currency sink');
assert.equal(listing.state.stock.lettuce,3);
const poor={...buyer,coins:3};assert.throws(()=>settleListing(poor,listing.state,row),/골드/);
const rich={...listing.state,coins:1_000_000_000_000};assert.throws(()=>settleListing(buyer,rich,row),/한도/);
const full={...buyer,stock:{lettuce:1_000_000}};assert.throws(()=>settleListing(full,listing.state,row),/창고/);
assert.throws(()=>reserveListing(seller,'berry_jam',2200,2),/재고/);
console.log('PASS v38 escrow, fees, bounded pricing, exact inventory transfer and state immutability');
