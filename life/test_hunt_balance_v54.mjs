import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {HUNT_ZONES,HUNT_BOSSES,huntLevel} from './hunt-data.js';
import {initHuntMastery,zoneAccess,bossAccess,masteryEnemy,hunterDamage,registerHuntKill,dailyHuntContracts,claimHuntContract,HUNT_MASTERY_GATES,HUNT_BOSS_TRIALS} from './hunt-balance-v54.js';
const old={xp:8960,coins:12345,hunt:{kills:83,bossDates:{'meadow:2026-10-18':true},materials:{'젤리 조각':21},gear:{weapon:'sun'},bossesOld:false}};
const copy=JSON.parse(JSON.stringify(old));
const m=initHuntMastery(old.hunt,HUNT_ZONES);
assert.equal(m.areas.meadow.cleared,true,'old boss record must count as historical win');
assert.equal(old.xp,copy.xp,'existing player XP stays untouched');
assert.equal(old.coins,copy.coins,'old main currency unchanged');
assert.deepEqual(old.hunt.materials,copy.hunt.materials);
assert.deepEqual(old.hunt.gear,copy.hunt.gear);
assert.equal(old.hunt.kills,copy.hunt.kills);
assert.equal(huntLevel(8960),57,'veteran life level unchanged');
assert.deepEqual(HUNT_MASTERY_GATES,[0,26,72,150]);
assert.equal(zoneAccess(old.hunt,HUNT_ZONES,0,57).ok,true);
assert.equal(zoneAccess(old.hunt,HUNT_ZONES,1,57).ok,false,'high life level alone does not unlock all hunt zones');
assert.equal(zoneAccess(old.hunt,HUNT_ZONES,1,57).reason.includes('숙련'),true);
assert.equal(zoneAccess(old.hunt,HUNT_ZONES,0,2).ok,false);
assert.equal(bossAccess(old.hunt,HUNT_ZONES,0).ok,false,'old clear flag does not pretend today\'s trial completed');
assert.equal(HUNT_BOSS_TRIALS.length,4);
const day='2026-10-20';
for(let i=0;i<8;i++)registerHuntKill(old.hunt,HUNT_ZONES,0,{day});
for(let i=0;i<2;i++)registerHuntKill(old.hunt,HUNT_ZONES,0,{day,elite:true});
assert.equal(bossAccess(old.hunt,HUNT_ZONES,0).ok,true,'two elites + ten kills unlock boss');
assert.equal(m.score,26);
assert.equal(zoneAccess(old.hunt,HUNT_ZONES,1,57).ok,true,'prior boss win + earned mastery unlock zone 2');
const elite=masteryEnemy(HUNT_ZONES[0].mobs[0],57,3,{elite:true});
const normal=masteryEnemy(HUNT_ZONES[0].mobs[0],57,3,{elite:false});
assert(elite.hp>normal.hp*2);
assert(elite.pattern==='rush');
assert(normal.hp>HUNT_ZONES[0].mobs[0].hp*4,'very high-level visitors should not one-shot every easy mob');
assert(normal.xp<=25,'basic enemy cannot hand out entire level');
assert(elite.xp<=35,'elite XP must be bounded');
const boss=masteryEnemy(HUNT_BOSSES[3],57,25,{boss:true});
assert(boss.hp>HUNT_BOSSES[3].hp);
assert(boss.xp<=150,'even final boss XP stays below one normal life level');
assert.equal(boss.pattern,'phase');
assert(hunterDamage(20,57,25,{elite:true})>hunterDamage(20,25,25,{elite:false}));
const daily=dailyHuntContracts(old.hunt,HUNT_ZONES,0,day);
assert.equal(daily[0].ready,true);
assert.equal(daily[1].ready,true);
assert.equal(daily[2].ready,false);
const claim=claimHuntContract(old.hunt,HUNT_ZONES,0,day,'patrol');
assert.equal(claim.ok,true);
assert.equal(claimHuntContract(old.hunt,HUNT_ZONES,0,day,'patrol').ok,false);
assert.equal(dailyHuntContracts(old.hunt,HUNT_ZONES,0,'2026-10-21')[0].ready,false,'daily objectives reset at new KST day');
assert.equal(old.hunt.masteryV54.score,26,'claiming contracts must not mint additional skill points');
const fresh={bossDates:{}};
initHuntMastery(fresh,HUNT_ZONES);
assert.equal(zoneAccess(fresh,HUNT_ZONES,2,57).ok,false);
const oldRuin={bossDates:{'ruins:2026-10-01':true}};
assert.equal(zoneAccess(oldRuin,HUNT_ZONES,3,57).ok,true,'veteran prior boss completion must not become locked');
// Verify integration points; never silently revert to old XP-per-kill or instant four-zone unlock.
const src=readFileSync(new URL('./hunt.js',import.meta.url),'utf8');
assert(src.includes('masteryEnemy(model,level(),zone.level,{elite})'));
assert(src.includes("const mastery=registerHuntKill(state.hunt,HUNT_ZONES,areaIndex"));
assert(src.includes("if(!trial.ok)return;"),'boss cannot appear without zone kill/elite challenge');
assert(src.includes('const permit=zoneAccess(state.hunt,HUNT_ZONES,index,level())'));
assert(src.includes('windupUntil'), 'attack telegraph used');
assert(src.includes('Math.hypot(hero.x-aimed.x,hero.z-aimed.z)'), 'dodging ring avoids hit');
assert(src.includes("dailyHuntContracts(state.hunt,HUNT_ZONES,i,today())"));
assert(src.includes("state.xp+=m.model.xp"),'combat XP still influences retained original player level, at reduced rate');
console.log('PASS v54: saved level and equipment preserved, mastery-based unlocks, gradual combat XP, elite/boss trials, telegraph dodges and daily contracts');
