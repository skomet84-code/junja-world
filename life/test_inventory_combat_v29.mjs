import assert from 'node:assert/strict';
import {initBag,BAG_TIERS,bagUsed,bagCapacity,bagFree,canStore,addBagItems,bagUpgrade,claimEventAutoSellTicket,useAutoSellTicket} from './inventory-v29.js';
import {POTIONS,ensurePotions,purchasePotion,consumePotion} from './combat-potions-v29.js';
import {RODS,FISH_BY_NAME,reelChallenge} from './life-systems-v20.js';
const state={coins:30000,fishStock:{'송사리':25},materials:{wood:5},crafted:{parcel:2},hunt:{materials:{crystal:4}},collection:['송사리']};
initBag(state);
assert.equal(bagUsed(state),36);
assert.equal(bagCapacity(state),36,'old items grandfathered, no deletion');
assert(!canStore(state,1));
let r=bagUpgrade(state);
assert(r.ok&&r.price===2600&&bagCapacity(state)===52);
assert.equal(state.coins,27400);
assert(addBagItems(state,'fish','붕어',1));assert.equal(bagUsed(state),37);
assert.equal(bagCapacity(state),52);
assert(claimEventAutoSellTicket(state,'2026-10'));
assert(!claimEventAutoSellTicket(state,'2026-10'),'no duplicate monthly tickets');
assert.equal(state.bag.autoSellTickets,1);
const old=state.coins;
r=useAutoSellTicket(state,FISH_BY_NAME,new Date('2026-10-18T12:00:00+09:00'),3);
assert(r.ok&&r.sold===26&&r.earnings>0);
assert.equal(state.fishStock['송사리'],0);
assert.equal(state.collection.length,1,'caught fish encyclopedia survives');
assert.equal(state.coins,old+r.earnings);
assert.equal(state.bag.autoSellTickets,0);
assert(!useAutoSellTicket(state,FISH_BY_NAME).ok,'spent ticket cannot be reused');
assert.equal(BAG_TIERS.length,7);
assert(RODS.length>=6);
for(const name of ['송사리','은빛 농어','황금 잉어']){
 const f=FISH_BY_NAME[name],basic=reelChallenge(f,'branch'),max=reelChallenge(f,'mythic');
 assert(max.hits<basic.hits,'expensive rod needs fewer successful taps');
 assert(max.maxMisses>basic.maxMisses,'expensive rod tolerates more misses');
 assert(max.seconds>basic.seconds,'expensive rod extends reel time');
 assert(max.width>basic.width,'expensive rod has wider target');
}
const pot={coins:1000,hunt:{potions:{hp:0,mp:0},starterPotionsV29:true}};
ensurePotions(pot);initBag(pot);
assert(purchasePotion(pot,'hp').ok);
assert.equal(pot.coins,810);
assert.equal(pot.hunt.potions.hp,3);
const p=consumePotion(pot,'hp',20,100,1000,0);
assert(p.ok&&p.amount===80&&p.value===100);
assert.equal(pot.hunt.potions.hp,2);
assert(!consumePotion(pot,'hp',10,100,1001,p.nextAt).ok);
assert(!consumePotion(pot,'hp',100,100,9000,0).ok);
assert.equal(POTIONS.length,4);
const legacy={coins:2000,hunt:{materials:{wood:80}}};initBag(legacy);
assert.equal(bagCapacity(legacy),80);
assert.equal(bagUsed(legacy),80);
console.log('PASS v29: grandfathered bag, upgrades, monthly auto-sell voucher, unique fish liquidation, rod grades, potions and cooldown');
