import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import {HOME_FURNITURE_V48,HOME_ROOMS_V48,HOME_SLOTS_V48,
 normalizeHomeV48,homeRoomV48,homePrestigeV48,buyHomeItemV48,arrangeHomeItemV48} from './home-interiors-v48.js';
import {estateWalkStep} from './estate-layout-v35.js';
assert.equal(HOME_ROOMS_V48.length,4);
assert.equal(HOME_SLOTS_V48,9);
assert.equal(Object.keys(HOME_FURNITURE_V48).length,12);
assert.equal(HOME_FURNITURE_V48.throne.rarity,'전설');
const legacy={level:2,wall:'pink',floor:'oak',furniture:['sofa','piano','table'],lastCare:'2026-10-18'};
const source=structuredClone(legacy),m=normalizeHomeV48(legacy);
assert.equal(m.level,2);
assert.deepEqual(m.items,legacy.furniture);
assert.equal(m.arrangements.length,3,'Legacy purchased furniture must automatically acquire a free slot');
assert.deepEqual(legacy,source,'Pure migration may not rewrite source save');
const a=homeRoomV48(legacy,0);
assert.equal(a.slots.length,9);
assert.equal(a.slots.filter(s=>s.item).length,3);
assert.equal(homePrestigeV48(legacy).score,10+1+6+2);
assert.throws(()=>homeRoomV48(legacy,2),/열리지/);
assert.throws(()=>buyHomeItemV48(legacy,'throne',900000),/4단계/);
assert.throws(()=>buyHomeItemV48(legacy,'library',200),/골드/);
assert.throws(()=>buyHomeItemV48(legacy,'piano',999999),/이미/);
assert.throws(()=>buyHomeItemV48(legacy,'admin_item',999999),/판매하지/);
const purchased=buyHomeItemV48(legacy,'library',75000);
assert.equal(purchased.cost,27000);
assert(purchased.next.furniture.includes('library'));
assert.equal(purchased.next.wall,'pink','Home cosmetic options must persist');
assert.equal(legacy.furniture.length,3,'No mutation of original cloud snapshot on new rare item purchase');
assert.equal(normalizeHomeV48(purchased.next).arrangements.length,4);
const placed=arrangeHomeItemV48(purchased.next,'library',1,8);
assert.equal(placed.changed,true);
assert.equal(placed.next.decorV48.find(p=>p.item==='library').room,1);
assert.equal(placed.next.decorV48.find(p=>p.item==='library').slot,8);
const before=normalizeHomeV48(placed.next).arrangements.find(p=>p.item==='sofa');
const swapped=arrangeHomeItemV48(placed.next,'library',before.room,before.slot);
assert.equal(swapped.swapped,'sofa');
assert.equal(swapped.next.decorV48.find(p=>p.item==='sofa').room,1);
assert.equal(swapped.next.decorV48.find(p=>p.item==='sofa').slot,8);
assert.equal(new Set(swapped.next.decorV48.map(p=>p.item)).size,4,'No duplicate furniture from swaps');
assert.equal(swapped.next.furniture.length,4,'No missing furniture from swaps');
assert.throws(()=>arrangeHomeItemV48(legacy,'throne',0,1),/가지고 있지/);
assert.throws(()=>arrangeHomeItemV48(legacy,'sofa',7,0),/열리지/);
const tampered={...purchased.next,decorV48:[
 {item:'sofa',room:0,slot:0},{item:'piano',room:0,slot:0},
 {item:'admin_item',room:0,slot:2},{item:'library',room:18,slot:1}
]};
const repaired=normalizeHomeV48(tampered);
assert.equal(repaired.arrangements.length,4);
assert.equal(new Set(repaired.arrangements.map(x=>x.room+':'+x.slot)).size,4);
assert.equal(repaired.arrangements.some(x=>x.room>=2),false);
const navCode=await readFile(new URL('./navigation.js',import.meta.url),'utf8');
const sandbox={};vm.runInNewContext(navCode,sandbox);
const navigator=sandbox.JunjaNavigation({width:600,height:500,walkable:(x,y)=>x>=10&&y>=10&&x<590&&y<490});
const actor={x:50,y:50,vx:0,vy:0,dir:0,stride:0};
const path=[{x:400,y:50}];
const advanced=navigator.advance(actor,path,1);
assert(Math.abs(advanced-10.25)<.01,'Main walk is 205 units/s, 0.05s collision-bound step = 10.25');
assert.equal(navigator.safe(actor),true);
const farmStep=estateWalkStep({x:0,z:0},{x:400,z:0},.05);
assert(Math.abs(farmStep.x-14)<.01,'Estate walk is 280 units/s');
console.log('PASS v48 12 furniture, 4 rooms, purchased legacy migration, swap positioning, rarity gate, nonmutating saves and 205/280 smooth walking');
