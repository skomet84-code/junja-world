import assert from 'node:assert/strict';
import {initCombat,purchaseSkill,purchaseEquipment,equipItem,equippedStats,skillStatus,spendSkill,incomingDamage} from './combat-progression-v30.js';
import {bagCapacity,bagUpgrade,initBag,purchaseAutoSellTicket,toggleFishProtection,useAutoSellTicket} from './inventory-v29.js';
import {FISH_BY_NAME} from './life-systems-v20.js';
import {sellFish} from './economy-v28.js';
const s={xp:320,coins:10000,hunt:{}};initCombat(s);
assert(!skillStatus(s,'strike',100).ok,'new skills require purchase');
assert(!purchaseSkill(s,'star').ok,'level gate');
assert(purchaseSkill(s,'strike').ok);assert.equal(s.coins,9350);
assert(!purchaseSkill(s,'strike').ok);assert.equal(s.coins,9350);
assert(!spendSkill(s,'strike',0,1000).ok);
assert.equal(spendSkill(s,'strike',50,1000).mp,38);
const loaded=JSON.parse(JSON.stringify(s));
assert(!skillStatus(loaded,'strike',100,3999).ok,'reload preserves cooldown');
assert(skillStatus(loaded,'strike',100,4000).ok);
const before=equippedStats(s);assert(purchaseEquipment(s,'bronze').ok);
assert(equipItem(s,'bronze'));assert.equal(equippedStats(s).attack,before.attack+4);
assert(!purchaseEquipment(s,'bronze').ok);assert(!equipItem(s,'sun'));
assert(purchaseEquipment(s,'leather').ok);assert(equipItem(s,'leather'));
assert.equal(equippedStats(s).maxHp,before.maxHp+15);
assert(incomingDamage(0,false,30)<incomingDamage(0,false,0));
assert(incomingDamage(3,true,30)>incomingDamage(0,true,30));
assert(incomingDamage(3,true,999)>0);
const old={coins:1e6,materials:{wood:400}};initBag(old);
for(let i=0;i<6;i++){const capacity=bagCapacity(old);assert(bagUpgrade(old).ok);assert(bagCapacity(old)>capacity,'each paid upgrade increases legacy bag capacity');}
const sale={coins:1000,fishStock:{'송사리':2,'황금 잉어':1}};
assert(purchaseAutoSellTicket(sale).ok);assert.equal(sale.coins,650);
toggleFishProtection(sale,'황금 잉어');
assert(!sellFish(sale,FISH_BY_NAME['황금 잉어']).ok);
assert.equal(useAutoSellTicket(sale,FISH_BY_NAME).sold,2);
assert.equal(sale.fishStock['황금 잉어'],1);assert.equal(sale.bag.autoSellTickets,0);
assert(purchaseAutoSellTicket(sale).ok);
assert(!useAutoSellTicket(sale,FISH_BY_NAME).ok);assert.equal(sale.bag.autoSellTickets,1,'empty/protected sale never consumes ticket');
assert(!purchaseEquipment({xp:320,coins:0},'bronze').ok);
console.log('PASS v30 purchase debit, level gates, persisted skill cooldown, equipment stats, damage reduction, legacy bag expansion and protected auto/manual sale');
