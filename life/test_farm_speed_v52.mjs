import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {FARM_BED_CENTERS,FARM_PLOT_COUNT,FARM_OLD_PLOTS,VILLAGE_WALK_SPEED,migrateVillageBeds} from './farm-plots-v52.js';
const game=readFileSync(new URL('./game.js',import.meta.url),'utf8');
const world=readFileSync(new URL('./world3d.js',import.meta.url),'utf8');
const now=1792465200000;
assert.equal(FARM_OLD_PLOTS,14);
assert.equal(FARM_PLOT_COUNT,21);
assert.equal(FARM_BED_CENTERS.length,21);
const prev=Array.from({length:14},(_,i)=>({crop:i%2?'strawberry':'pumpkin',at:now-i*140000,meta:{originalSlot:i}}));
const oldCoords=Array.from({length:14},(_,i)=>({x:816+(i%7)*79,y:1171+Math.floor(i/7)*79}));
assert.deepEqual(FARM_BED_CENTERS.slice(0,14),oldCoords,'old bed locations/indices must be identical');
const expanded=migrateVillageBeds(prev,now);
assert.equal(expanded.length,21,'7 more plantable fields');
assert.deepEqual(expanded.slice(0,14),prev,'existing crop type, timestamp and metadata must survive');
assert(expanded.slice(14).every(b=>b.crop===null&&b.at===0),'new plots must not mint free crops');
const refreshed=migrateVillageBeds(expanded,now+100000);
assert.deepEqual(refreshed,expanded,'subsequent login must not reset previous or expanded beds');
const fresh=migrateVillageBeds(undefined,now);
assert.equal(fresh.length,21);
assert.equal(fresh.filter(b=>b.crop!==null).length,3,'fresh players get exactly 3 starter crops');
assert.equal(fresh[0].at,now-90000);
const emptyOld=migrateVillageBeds(Array.from({length:14},()=>({crop:null,at:0})),now);
assert(emptyOld.every(b=>b.crop===null),'existing harvested beds must not receive free crops after upgrade');
assert.equal(VILLAGE_WALK_SPEED,228);
assert(VILLAGE_WALK_SPEED>205&&VILLAGE_WALK_SPEED<235,'speed should be a modest upgrade');
assert(game.includes("state.beds=migrateVillageBeds(state.beds)"),'game must migrate saves before farm rendering');
assert(game.includes("navigation.advance(player,path,dt,VILLAGE_WALK_SPEED)"),'touch-to-walk should be faster');
assert(game.includes("navigation.advance(player,[target],dt,VILLAGE_WALK_SPEED)"),'desktop walk should match speed');
assert(game.includes("beds:bedCenters"),'3D world receives all new plots');
assert(world.includes("beds.forEach")&&world.includes("cropGroups[i]"),'3D crops should render from dynamic plot array');
console.log('PASS v52: 14→21 beds, crop/time preservation, repeat-save safety, 3D planting, both movement modes +11%');
