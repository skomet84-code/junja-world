import assert from 'node:assert/strict';
import {ECONOMY_POLICY,BAITS,economyCeiling,initEconomy,credit,debit,moneyHistory,marketDay,quoteFish,initializeFishStock,addFishStock,sellFish,buyBait,chooseBait,useBait,adjustCatchRoll} from './economy-v28.js';
import {FISH,FISH_BY_NAME} from './life-systems-v20.js';
const day=new Date('2026-10-17T10:00:00+09:00'),tomorrow=new Date('2026-10-18T10:00:00+09:00');
const s={coins:1000,xp:0,collection:['송사리'],fishRecords:{}};
const e=initEconomy(s,day);
assert.equal(s.coins,1000);assert.equal(e.earned,0);
assert.equal(ECONOMY_POLICY.starterG,5000);
assert.equal(debit(s,1500,'shop','unaffordable',day).ok,false);
assert.equal(s.coins,1000,'rejected checkout must not change coin balance');
assert.equal(debit(s,100,'shop','dress',day).ok,true);assert.equal(s.coins,900);
let bonus=credit(s,100,'achievement','one-time starter achievement',1,day);
assert.equal(bonus.amount,100);assert.equal(s.coins,1000);
const c=economyCeiling('hunt',1);assert(c>0);
const first=credit(s,c,'hunt','fight',1,day);
assert.equal(first.amount,c,'earn full before daily cap');
const lowered=credit(s,500,'hunt','repeat',1,day);
assert(lowered.amount<=125 && lowered.amount>=1,'earnings should reduce to 25% after cap');
const beyond=credit(s,c*2,'hunt','repeat more',1,day);
assert(beyond.amount<Math.floor(c*.4),'long grinding must not mint unlimited full rewards');
const old=s.coins;
credit(s,400,'harvest','crop',1,tomorrow);
assert(s.economy.day.endsWith('18'),'new day resets earn budgets');
assert.equal(s.economy.earned,400);
assert.equal(s.coins,old+400);
assert(s.economy.journal.length>=5 && moneyHistory(s)[0].reason==='crop');
initializeFishStock(s);
const fish=FISH_BY_NAME['송사리'];assert(fish);
addFishStock(s,fish.name,2);
let original=s.fishStock[fish.name],coins=s.coins;
const sale=sellFish(s,fish,tomorrow,1);
assert(sale.ok&&sale.amount>0);
assert.equal(s.fishStock[fish.name],original-1);
assert(s.coins>coins);
assert.equal(s.collection.length,1,'selling does not erase historical aquarium discovery');
assert.equal(sellFish(s,fish,tomorrow,1).ok,true);
assert.equal(sellFish(s,fish,tomorrow,1).ok,false,'cannot sell unowned fish a third time');
const before=s.coins;
assert(buyBait(s,'basic',tomorrow).ok);
assert.equal(s.coins,before-180);
chooseBait(s,'basic');
assert.equal(useBait(s).id,'basic');assert.equal(s.baitInventory.basic,9);
assert(adjustCatchRoll(.5,BAITS[2])>.5);
assert.equal(adjustCatchRoll(.5,null),.5);
assert.equal(quoteFish(fish,day),quoteFish(fish,day),'NPC quote must remain deterministic throughout same day');
assert.equal(marketDay(day).day,'2026-10-17');
assert.equal(new Set(FISH.map(x=>x.name)).size,70);
const admin={coins:100000000};initEconomy(admin,day);assert.equal(admin.coins,100000000,'legacy operator preview money preserved');
assert.equal(credit(admin,100,'achievement','bonus',1,day).amount,100);
assert.equal(debit(admin,800000,'shop','royal furnishing',day).ok,true);
const caps={coins:1000};assert.equal(debit(caps,-2).ok,false);assert.equal(credit(caps,Number.NaN).ok,false);
console.log('PASS v28: 5000G fresh start while existing 1000G save is preserved, legitimate 100m saves, auditable faucet/sinks, diminishing returns, real fish stock, daily prices and anti-duplicate sale');
