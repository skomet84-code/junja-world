import assert from 'node:assert/strict';
import {startingEconomy} from './secure-economy-v36.js';
import {selectProfession} from './professions-v39.js';
import {NPC_SHOPPERS,NPC_ORDER_DAILY_GROSS_CAP,NPC_ORDER_DAILY_LIMIT,
 residentBuyerQuote,fulfillResidentOrder,npcOrdersView} from './resident-demand-v44.js';
const t=new Date('2026-10-19T12:00:00+09:00');
const d=new Date('2026-10-20T12:00:00+09:00');
assert.equal(Object.keys(NPC_SHOPPERS).length,3);
const quotes=Object.keys(NPC_SHOPPERS).map(k=>residentBuyerQuote(k,t));
assert(quotes.every(q=>q.tax===Math.ceil(q.gross*.12)&&q.net===q.gross-q.tax));
assert(quotes.every(q=>q.gross>0&&q.gross<=6000));
assert.deepEqual(residentBuyerQuote('tobi',t),residentBuyerQuote('tobi',t),'Day quote is immutable server calculation');
assert.notEqual(residentBuyerQuote('tobi',t).day,residentBuyerQuote('tobi',d).day);
assert.throws(()=>residentBuyerQuote('hacker',t),/존재하지/);
let state=startingEconomy();state.coins=9000;state.stock={berry_box:3,artisan_tart:1};
state.workshops={farmer:{level:1},chef:{level:2}};
state=selectProfession(state,'farmer',{},t).next;
assert.equal(npcOrdersView(state,t).orders.find(q=>q.npcId==='tobi').canSell,true);
assert.throws(()=>fulfillResidentOrder(state,'rina',t),/현재 직업/);
const sold=fulfillResidentOrder(state,'tobi',t);
assert.equal(sold.next.stock.berry_box,2);
assert.equal(sold.next.coins,state.coins+sold.quote.net);
assert.equal(sold.next.residentOrders.used.length,1);
assert.equal(sold.next.residentOrders.spent,sold.quote.gross);
assert.equal(state.stock.berry_box,3,'Economic snapshot remains immutable');
assert.throws(()=>fulfillResidentOrder(sold.next,'tobi',t),/이미 납품/);
const bad=structuredClone(state);bad.stock.berry_box=-1;
assert.throws(()=>fulfillResidentOrder(bad,'tobi',t),/실제 생산품/);
const noBuilding=structuredClone(state);delete noBuilding.workshops.farmer;
assert.throws(()=>fulfillResidentOrder(noBuilding,'tobi',t),/사업장/);
const maxed=structuredClone(state);maxed.coins=1_000_000_000_000;
assert.throws(()=>fulfillResidentOrder(maxed,'tobi',t),/잔액/);
const two=structuredClone(sold.next);
two.residentOrders={day:residentBuyerQuote('tobi',t).day,used:['tobi','rina'],spent:8000};
assert.equal(npcOrdersView(two,t).remaining,0);
assert.throws(()=>fulfillResidentOrder(two,'tobi',t),/이미 납품/);
const limit=structuredClone(sold.next);
limit.residentOrders={day:residentBuyerQuote('tobi',t).day,used:['rina'],spent:NPC_ORDER_DAILY_GROSS_CAP};
assert.throws(()=>fulfillResidentOrder(limit,'tobi',t),/예산/);
const forged=structuredClone(state);forged.residentOrders={day:residentBuyerQuote('tobi',t).day,used:['tobi','tobi'],spent:1000};
assert.throws(()=>fulfillResidentOrder(forged,'tobi',t),/장부 검증/);
assert.equal(npcOrdersView(sold.next,d).used,0,'Daily KST window resets by server day');
assert.equal(NPC_ORDER_DAILY_LIMIT,2);
console.log('PASS v44 bounded server NPC quotes, taxed payouts, one-stock consumption, daily replay cap, KST reset and immutable original state');
